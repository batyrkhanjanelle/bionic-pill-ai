plt.title("Confusion Matrix")
plt.show()

"""## Patient Simulation and AI Prediction

Для демонстрации практического применения модели
была реализована симуляция пациента во времени.

Параметры пациента изменяются динамически,
а модель оценивает риск нарушения терапии на каждом шаге.
"""

import random
import time
from IPython.display import clear_output

risk_history = []

for step in range(20):

    # симуляция пациента
    age = random.randint(20, 70)
    dose = random.randint(150, 350)
    pH = random.uniform(1.5, 7.5)
    missed_doses = random.randint(0, 5)
    heart_rate = random.randint(60, 110)

    patient = [[age, dose, pH, missed_doses, heart_rate]]

    # прогноз модели
    risk = rf_model.predict(patient)[0]

    risk_history.append(risk)

    clear_output(wait=True)

    print("PATIENT STATE")
    print("----------------------")
    print("Age:", age)
    print("Dose:", dose)
    print("pH:", round(pH,2))
    print("Missed doses:", missed_doses)
    print("Heart rate:", heart_rate)

    if risk == 1:
        print("⚠ High risk of therapy non-adherence")
    else:
        print("✔ Low risk")

    # график риска
    plt.figure(figsize=(6,3))
    plt.plot(risk_history, marker='o')
    plt.title("Risk Dynamics")
    plt.xlabel("Time step")
    plt.ylabel("Risk")
    plt.ylim(-0.1,1.1)
    plt.grid(True)
    plt.show()

    time.sleep(1)

