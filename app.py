np.random.seed(42)

"""## Математическая модель высвобождения лекарств

Высвобождение лекарственного вещества описывается экспоненциальной моделью первого порядка:

$$
C(t) = D \cdot (1 - e^{-kt})
$$

где:
- C(t) — количество высвобожденного вещества  
- D — доза  
- k — коэффициент скорости  
- t — время  

Модель широко используется в фармакокинетике.

функция + *интерактив*
"""

from ipywidgets import interact, FloatSlider
import numpy as np
import matplotlib.pyplot as plt

def drug_release(time, dose, speed):
    return dose * (1 - np.exp(-speed * time))


@interact(
    dose=FloatSlider(min=50, max=500, step=10, value=200),
    speed=FloatSlider(min=0.05, max=1.0, step=0.05, value=0.3)
)
def interactive_plot(dose, speed):
    time = np.linspace(0, 10, 100)
    released = drug_release(time, dose, speed)

    plt.figure(figsize=(8,4))
    plt.plot(time, released)
    plt.fill_between(time, released, alpha=0.3)
    plt.xlabel("Time (hours)")
    plt.ylabel("Released drug (mg)")
    plt.title("Controlled Drug Release")
    plt.grid(True)
    plt.show()

"""## Визуализация динамики

Анимации демонстрирует процесс высвобождения лекарственного вещества
и влияние параметров на скорость доставки препарата.
"""

from matplotlib.animation import FuncAnimation
from IPython.display import HTML

